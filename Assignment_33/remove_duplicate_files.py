def calculate_checksum(file_name):
    f_obj = open(file_name, "rb")

    h_obj = hashlib.md5()
    buffer = f_obj.read(1024)

    while len(buffer) > 0:
        h_obj.update(buffer)
        buffer = f_obj.read(1024)

    f_obj.close()

    return h_obj.hexdigest()

def find_duplicate(directory_name):
    if not os.path.exists(directory_name):
        print("Error: Path is invalid")
        sys.exit(1)
    
    if not os.path.isdir(directory_name):
        print(f"Error: {directory_name} is not a directory")
        sys.exit(1)

    duplicate = dict()

    for folder_name, sub_folders, file_names in os.walk(directory_name):
        for f_name in file_names:
            f_name = os.path.join(folder_name, f_name)
            check_sum = calculate_checksum(f_name)

            if check_sum in duplicate:
                duplicate[check_sum].append(f_name)
            else:
                duplicate[check_sum] = [f_name]

    return duplicate

