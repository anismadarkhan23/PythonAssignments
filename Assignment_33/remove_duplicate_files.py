def delete_duplicate(directory_name):
    global start_time

    unfiltered_dict = find_duplicate(directory_name)
    duplicate_files_dict = list(filter(lambda x: len(x) > 1, unfiltered_dict.values()))

    count = 0
    total_deleted = 0
    check_sum_list = list()
    deleted_file_path_list = list()
    scanned_files_list = list()

    for folder_name, sub_folders, file_names in os.walk(directory_name):
        for f_name in file_names:
            f_name = os.path.join(folder_name, f_name)
            scanned_files_list.append(f_name)

    for duplicate_files in duplicate_files_dict:
        for duplicate_file in duplicate_files:
            count += 1
            if count > 1:
                check_sum_list.append(calculate_checksum(duplicate_file))
                deleted_file_path_list.append(os.path.abspath(duplicate_file))
                os.remove(duplicate_file)
                total_deleted += 1
        count = 0

    end_time = time.strftime("%I:%M:%S %p")

    generate_log_report("MarvellousDuplicateRemoval", directory_name, scanned_files_list,
                        check_sum_list, deleted_file_path_list, total_deleted, 
                        start_time, end_time)
            
